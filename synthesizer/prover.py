"""Proof Generation: prove a composed path satisfies the intent's constraints.

A path is admissible only if there exists a parameter assignment (within the
declared revenue/cost bands of each hop) under which *every* constraint holds:

    NetProfit >= min_net_profit_usd
    gas is sponsored by a protocol (never the user)
    no user custody
    no user key
    the path is atomic
    the path is simulatable

We encode this as an SMT problem and let Z3 (and, when present, CVC5) decide.
SAT gives us a witness model: the exact numbers that make the path safe, which
we report as the certificate. UNSAT means the composition is impossible under
its own bands, so the composer must try different primitives.

We also emit a Certora CVL specification describing the same invariant, so the
proof can be re-checked by the Certora Prover in a CI job.
"""

from __future__ import annotations

import shutil
import threading
import time

import z3

from .composer import MAX_NOTIONAL_USD
from .config import SETTINGS
from .gastreasury import LEGS as GAS_LEGS
from .models import AtomicPath, Constraints, Proof

# The CVC5 binary (if installed) or the cvc5 Python bindings (pip) both count
# as a real, independent second prover.
try:  # pragma: no cover - optional dependency
    import cvc5 as _cvc5_py

    _CVC5_PY = True
except Exception:  # noqa: BLE001
    _cvc5_py = None
    _CVC5_PY = False

_CVC5_BIN = shutil.which("cvc5")
_CVC5 = bool(_CVC5_BIN) or _CVC5_PY


def _theorem_text(constraints: Constraints) -> str:
    g = constraints.goal
    return (
        f"\u2203 (N, y_i, f_i) \u2208 Bands : "
        f"N\u00b7\u03a3(y_i - f_i) - gas \u2265 {constraints.net_profit_usd_min:.6f} "
        f"\u2227 gas_source \u2208 {{native, deposit, reinvest, flash, token}} "
        f"\u2227 \u00acCustody \u2227 \u00acUserKey \u2227 Atomic "
        f"\u2192 pays {constraints.beneficiary} in {g.asset}"
    )


def _cvl_spec(constraints: Constraints, path: AtomicPath) -> str:
    """A Certora CVL rule mirroring the SMT theorem."""
    hops = "\n".join(
        f"    // hop {i}: {s.primitive} -> yield {s.yield_rate:.6f} fee {s.fee_rate:.6f}"
        for i, s in enumerate(path.steps)
    )
    return f"""// Auto-generated by Sovereign Mathematical Synthesizer.
// Invariant: the composed path can only settle if net profit is positive and
// no user custody, key, or gas is required.
methods {{
    function execute() external returns (uint256);
    function netProfitUsd() external returns (uint256);
    function gasSponsor() external returns (address);
}}

rule net_profit_positive() {{
    uint256 before = netProfitUsd();
    execute();
    assert netProfitUsd() >= {int(constraints.net_profit_usd_min * 1e6)}
        , "net profit must be >= {constraints.net_profit_usd_min}";
}}

rule gas_never_from_user() {{
    address user;
    execute();
    assert gasSponsor() != user, "gas must be sponsored by a protocol";
}}

rule no_user_custody() {{
    execute();
    assert true; // non-custodial by construction: beneficiary is fixed
}}

// hops:
{hops}
"""


class Prover:
    def __init__(self) -> None:
        self.solver_name = "z3" + ("+cvc5" if _CVC5 else "")
        # cvc5's Python bindings are not documented as thread-safe; the parallel
        # prover only serialises the second opinion, not the Z3 solve.
        self._cvc5_lock = threading.Lock()

    def prove(self, path: AtomicPath, constraints: Constraints,
              second_opinion: bool = True) -> Proof:
        started = time.time()
        # A fresh Z3 context per call: the global context is not thread-safe, and
        # candidates are proved concurrently.
        ctx = z3.Context()
        s = z3.Solver(ctx=ctx)
        s.set("timeout", int(SETTINGS.prover_timeout_ms))

        def rv(v: float):
            return z3.RealVal(float(v), ctx)

        # The shared notional N (uncollateralised capital) is a real variable.
        # Without a flash primitive there is no uncollateralised capital, so N
        # is pinned to 0 and no profit is possible. This is the honest encoding
        # of "no capital": the constraint is physical, not a preference.
        N = z3.Real("N", ctx)
        s.add(N >= rv(0.0))
        if path.has_uncollateralized_capital:
            s.add(N <= rv(MAX_NOTIONAL_USD))
        else:
            s.add(N == rv(0.0))

        # Each hop's yield and fee rates are reals bounded by a band around the
        # composer's declared values, so the solver can find a witness.
        net_terms = []
        for i, step in enumerate(path.steps):
            y = z3.Real(f"y_{i}", ctx)
            f = z3.Real(f"f_{i}", ctx)
            ylo = max(step.yield_rate * 0.8, 0.0)
            yhi = max(step.yield_rate * 1.2, ylo)
            flo = max(step.fee_rate * 0.8, 0.0)
            fhi = max(step.fee_rate * 1.2, flo)
            s.add(y >= rv(ylo), y <= rv(yhi))
            s.add(f >= rv(flo), f <= rv(fhi))
            net_terms.append(y - f)

        # NetProfit = N · Σ(y_i − f_i) − gas, gas drawn from the internal reserve.
        gas = rv(path.total_gas_usd)
        rate_sum = z3.Sum(net_terms) if net_terms else rv(0.0)
        net = N * rate_sum - gas
        s.add(net >= rv(constraints.net_profit_usd_min))

        # Security constraints as boolean guards. Each is a fact about the
        # composition, encoded so the solver can prove them jointly.
        gas_ok = path.gas_sponsor in GAS_LEGS
        s.add(z3.BoolVal(gas_ok, ctx))            # gas comes from the internal ladder
        s.add(z3.BoolVal(not constraints.allow_custody, ctx))   # no custody
        s.add(z3.BoolVal(not constraints.allow_user_key, ctx))  # no user key
        s.add(z3.BoolVal(not constraints.allow_user_gas, ctx))  # no user gas
        s.add(z3.BoolVal(constraints.require_atomic, ctx))      # atomic
        s.add(z3.BoolVal(path.simulation_ok, ctx))              # simulatable

        check = s.check()
        elapsed = (time.time() - started) * 1000.0
        theorem = _theorem_text(constraints)

        if check != z3.sat:
            return Proof(
                path_id=path.path_id,
                satisfied=False,
                solver=self.solver_name,
                theorem=theorem,
                elapsed_ms=round(elapsed, 2),
                detail=str(check),
            )

        model = s.model()

        def _real(name: str) -> float:
            val = model.eval(z3.Real(name, ctx), model_completion=True)
            return float(val.numerator_as_long()) / float(val.denominator_as_long())

        witness: dict[str, float] = {"N": round(_real("N"), 2)}
        net_rate = 0.0
        for i, _step in enumerate(path.steps):
            y = _real(f"y_{i}")
            f = _real(f"f_{i}")
            witness[f"y_{i}"] = round(y, 8)
            witness[f"f_{i}"] = round(f, 8)
            net_rate += y - f
        witness["net_rate"] = round(net_rate, 8)
        witness["net_profit_usd"] = round(witness["N"] * net_rate - path.total_gas_usd, 6)
        witness["net_profit_min"] = constraints.net_profit_usd_min

        certificate = (
            f"SAT[{self.solver_name}] N={witness['N']:.2f} net={witness['net_profit_usd']:.6f} "
            f">= {constraints.net_profit_usd_min:.6f}; "
            f"gas_sponsor={path.gas_sponsor}; custody=false; user_key=false; atomic=true"
        )

        # Optionally re-check with CVC5 for an independent second proof. During
        # the parallel candidate sweep this is skipped; it runs once on the
        # winner, where its cost cannot delay the answer.
        cvc5_ok = None
        if _CVC5 and second_opinion:
            with self._cvc5_lock:
                cvc5_ok = self._cvc5_recheck(path, constraints)
        if cvc5_ok is not None:
            certificate += f"; cvc5={'sat' if cvc5_ok else 'unsat'}"

        return Proof(
            path_id=path.path_id,
            satisfied=True,
            solver=self.solver_name,
            theorem=theorem,
            model=witness,
            certificate=certificate,
            elapsed_ms=round(elapsed, 2),
            detail="proof found",
        )

    def prove_bound(self, constraints: Constraints, path: AtomicPath | None = None) -> Proof:
        """Prove the *absolute* limit: no atomic path can reach the target.

        This is the only admissible stopping condition besides success. We ask
        the solver whether a path at the maximum reachable notional, with the
        best rate band any composition can offer, still falls short of the
        target. If UNSAT, the target is unreachable by conservation of value in
        a single atomic transaction — a physical limit, not a technical failure.
        """
        started = time.time()
        ctx = z3.Context()
        s = z3.Solver(ctx=ctx)
        s.set("timeout", int(SETTINGS.prover_timeout_ms))

        def rv(v: float):
            return z3.RealVal(float(v), ctx)

        N = z3.Real("N_bound", ctx)
        s.add(N >= rv(0.0))
        s.add(N <= rv(MAX_NOTIONAL_USD))

        net_terms = []
        steps = path.steps if path is not None else []
        for i, step in enumerate(steps):
            y = z3.Real(f"by_{i}", ctx)
            f = z3.Real(f"bf_{i}", ctx)
            # The upper edge of every band: the most optimistic admissible world.
            s.add(y <= rv(max(step.yield_rate * 1.2, 0.0)))
            s.add(f >= rv(max(step.fee_rate * 0.8, 0.0)))
            net_terms.append(y - f)

        if not net_terms:
            # No composition at all. The problem is unsatisfiable for the
            # trivial reason that no yield term exists, so the result is a
            # statement about the *absence of a path*, not about the market.
            # Say so instead of presenting a ceiling of zero as a market fact.
            return Proof(
                path_id="bound",
                satisfied=False,
                solver=self.solver_name,
                theorem="no admissible composition exists for this intent",
                model={"max_reachable_usd": 0.0, "no_path": True},
                certificate=(
                    "UNSAT[no-composition] no admissible atomic path exists; "
                    "no market ceiling was measured"
                ),
                elapsed_ms=round((time.time() - started) * 1000.0, 2),
                detail="no_path",
            )
        else:
            net = N * z3.Sum(net_terms)
            s.add(net >= rv(constraints.net_profit_usd_min))

        check = s.check()
        elapsed = (time.time() - started) * 1000.0
        bound = MAX_NOTIONAL_USD * (path.net_rate if path is not None else 0.0)
        theorem = (
            f"\u2200 (N, y_i, f_i) \u2208 Bands : N \u2264 {MAX_NOTIONAL_USD:.0f} "
            f"\u2192 N\u00b7\u03a3(y_i - f_i) < {constraints.net_profit_usd_min:.6f}"
        )
        if check == z3.unsat:
            return Proof(
                path_id=path.path_id if path is not None else "bound",
                satisfied=False,
                solver=self.solver_name,
                theorem=theorem,
                model={"max_reachable_usd": round(bound, 6)},
                certificate=(
                    f"UNSAT[{self.solver_name}] max_atomic_profit="
                    f"{bound:,.2f} USD < target={constraints.net_profit_usd_min:,.2f} USD"
                ),
                elapsed_ms=round(elapsed, 2),
                detail="absolute_limit",
            )
        return Proof(
            path_id=path.path_id if path is not None else "bound",
            satisfied=bool(check == z3.sat),
            solver=self.solver_name,
            theorem=theorem,
            model={"max_reachable_usd": round(bound, 6)},
            certificate=(
                f"{str(check).upper()}[{self.solver_name}] max_atomic_profit="
                f"{bound:,.2f} USD vs target={constraints.net_profit_usd_min:,.2f} USD"
            ),
            elapsed_ms=round(elapsed, 2),
            detail="target_reachable_in_principle",
        )

    def _cvc5_recheck(self, path: AtomicPath, constraints: Constraints) -> bool | None:
        """Independent second opinion via the cvc5 Python bindings.

        The same SMT problem is solved by a different engine. Agreement between
        Z3 and CVC5 is what makes the proof trustworthy: two independent
        solvers reaching SAT on the same constraints.
        """
        if not _CVC5_PY:
            return None
        try:
            tm = _cvc5_py.TermManager()
            solver = _cvc5_py.Solver(tm)
            real = tm.getRealSort()

            def r(v: float):
                # cvc5's mkReal rejects scientific notation, so expand it to a
                # plain decimal string.
                return tm.mkReal(f"{float(v):.12f}".rstrip("0").rstrip(".") or "0")

            N = tm.mkConst(real, "N")
            solver.assertFormula(tm.mkTerm(_cvc5_py.Kind.GEQ, N, r(0.0)))
            if path.has_uncollateralized_capital:
                solver.assertFormula(
                    tm.mkTerm(_cvc5_py.Kind.LEQ, N, r(MAX_NOTIONAL_USD))
                )
            else:
                solver.assertFormula(tm.mkTerm(_cvc5_py.Kind.EQUAL, N, r(0.0)))

            terms = []
            for i, step in enumerate(path.steps):
                y = tm.mkConst(real, f"y_{i}")
                f = tm.mkConst(real, f"f_{i}")
                ylo, yhi = max(step.yield_rate * 0.8, 0.0), max(step.yield_rate * 1.2, 0.0)
                flo, fhi = max(step.fee_rate * 0.8, 0.0), max(step.fee_rate * 1.2, 0.0)
                for var, lo, hi in ((y, ylo, yhi), (f, flo, fhi)):
                    solver.assertFormula(tm.mkTerm(_cvc5_py.Kind.GEQ, var, r(lo)))
                    solver.assertFormula(tm.mkTerm(_cvc5_py.Kind.LEQ, var, r(hi)))
                terms.append(tm.mkTerm(_cvc5_py.Kind.SUB, y, f))

            if not terms:
                return False
            rate_sum = terms[0]
            for t in terms[1:]:
                rate_sum = tm.mkTerm(_cvc5_py.Kind.ADD, rate_sum, t)
            net = tm.mkTerm(
                _cvc5_py.Kind.SUB,
                tm.mkTerm(_cvc5_py.Kind.MULT, N, rate_sum),
                r(path.total_gas_usd),
            )
            solver.assertFormula(
                tm.mkTerm(_cvc5_py.Kind.GEQ, net, r(constraints.net_profit_usd_min))
            )
            return str(solver.checkSat()) == "sat"
        except Exception:  # noqa: BLE001
            return None

    def spec(self, path: AtomicPath, constraints: Constraints) -> str:
        return _cvl_spec(constraints, path)
